# Tema 1: SELECT, WHERE, ORDER BY

## ¿Qué aprendí?
- **SELECT**: Elegir qué columnas mostrar
- **WHERE**: Filtrar filas que cumplen condiciones
- **ORDER BY**: Ordenar resultados (ASC/DESC)

## Consultas incluidas
1. Filtro de Tecnología con cantidad >= 2
2. Filtro de Oficina con cantidad > 1
3. Filtro por fecha después del 17-ene-2024
4. Todas las ventas de Bogotá
5. Productos ordenados por precio

## Tabla usada: `ventas`
| Columnas | tipo de dato |
|----------|--------------|
| id_venta | número |
| producto | texto |
| categoria | texto |
| cantidad | número |
| precio_unitario | número |
| ciudad | texto |
| fecha | fecha |
